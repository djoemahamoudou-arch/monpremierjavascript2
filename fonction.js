// J'utilise la fonction additionner (chiffre1, chiffre2) pour calculer la somme de deux nombres

function addition(chiffre1, chiffre2) {
    let resultat = chiffre1 + chiffre2;
    return resultat;

};

let resultatAddition = addition(15, 8);


console.log("Résultat de d'addition : ", resultatAddition);




